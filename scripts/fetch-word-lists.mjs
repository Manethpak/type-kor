import { mkdir, writeFile } from "node:fs/promises";

const endpoint =
  "https://datasets-server.huggingface.co/rows?dataset=seanghay%2Fkhmer-search-frequency&config=default&split=train";
const output = new URL("../src/data/wordLists.generated.ts", import.meta.url);
const pageSize = 100;
const requestedWords = 1000;

const rows = [];
for (let offset = 0; offset < requestedWords; offset += pageSize) {
  const response = await fetch(`${endpoint}&offset=${offset}&length=${pageSize}`);
  if (!response.ok) throw new Error(`Hugging Face request failed: ${response.status}`);
  const page = await response.json();
  rows.push(...page.rows.map(({ row }) => row));
}

if (rows.length < requestedWords) {
  throw new Error(`Expected ${requestedWords} rows, received ${rows.length}`);
}

const words = rows.slice(0, requestedWords).map(({ word }) => word);
if (words.some((word) => typeof word !== "string" || !word || /\s/u.test(word))) {
  throw new Error("Dataset contains an empty or whitespace-bearing word");
}
if (new Set(words).size !== words.length) throw new Error("Dataset contains duplicate words");

const generated = `// Generated by scripts/fetch-word-lists.mjs. Do not edit manually.\n// Source: ${endpoint}\n\nexport const frequencyWords1000 = ${JSON.stringify(words, null, 2)} as const;\n`;
await mkdir(new URL("../src/data/", import.meta.url), { recursive: true });
await writeFile(output, generated);
